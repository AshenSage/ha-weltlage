import {build} from 'esbuild';
import {cp,mkdir,rm,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=process.cwd(),out=resolve(root,'custom_components/weltlage/frontend');
await mkdir(out,{recursive:true});
const pkg=JSON.parse(await readFile('package.json','utf8'));
await build({entryPoints:['frontend_src/cesium/card.js'],outfile:resolve(out,'weltlage-card.js'),bundle:true,format:'esm',minify:true,target:'es2022',legalComments:'linked',define:{__WELTLAGE_VERSION__:JSON.stringify(pkg.version)},loader:{'.css':'text'},banner:{js:'/* Weltlage Cesium globe. See THIRD_PARTY.md for code/data licences. */'}});
await build({entryPoints:['frontend_src/cesium/satellite-worker.js'],outfile:resolve(out,'satellite-worker.js'),bundle:true,format:'esm',minify:true,target:'es2022',legalComments:'eof'});
await rm(resolve(out,'cesium'),{recursive:true,force:true});
for(const name of ['Workers','Assets','ThirdParty','Widgets'])await cp(resolve(root,'node_modules/cesium/Build/Cesium',name),resolve(out,'cesium',name),{recursive:true});
await cp('node_modules/cesium/LICENSE.md',resolve(out,'cesium/LICENSE.md'));
await cp('frontend_src/vendor/GODS-EYE-LICENSE',resolve(out,'GODS-EYE-LICENSE.txt'));
await cp('THIRD_PARTY.md',resolve(out,'THIRD_PARTY.md'));
await cp('LICENSE',resolve(out,'LICENSE.txt'));
await mkdir(resolve(out,'licenses'),{recursive:true});
for(const [source,name] of [['node_modules/@mapbox/vector-tile/LICENSE.txt','vector-tile.txt'],['node_modules/pbf/LICENSE','pbf.txt'],['node_modules/@mapbox/point-geometry/LICENSE','point-geometry.txt']])await cp(source,resolve(out,'licenses',name));
await writeFile(resolve(out,'build.json'),JSON.stringify({version:pkg.version,cesium:pkg.devDependencies.cesium},null,2)+'\n');
await rm(resolve(out,'weltlage-globe.js'),{force:true});
console.log('Built card, satellite worker and local Cesium runtime assets');
